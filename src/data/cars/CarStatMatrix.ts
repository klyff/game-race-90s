export const CAR_STAT_MATRIX_SIZE = CAR_STAT_MATRIX.length;

export function isCarStatMatrixIndex(n: number): boolean {
  return Number.isInteger(n) && n >= 1 && n <= CAR_STAT_MATRIX_SIZE;
}

export function carStatRow(n: number): CarStatIdentity {
  const row = CAR_STAT_MATRIX[n - 1];
  if (row === undefined || row.n !== n) {
    throw new Error(`CarStatMatrix has no row ${n}`);
  }
  return row;
}
