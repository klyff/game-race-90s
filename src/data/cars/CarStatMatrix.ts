/**
 * One physics identity per matrix_car folder `N_hero` (1–30).
 *
 * Hyphen shop ids (`car-1`, `car-6-tank`) and underscore clock ids (`car_18`)
 * that share a matrix number share this row. Collision boxes stay on the sheet;
 * this file only authors handling, perk and home world.
 *
 * Thunder Basin (1, 2, 5, 21) is the teaching band: slower than the old Marauder
 * 78 u/s, so the +18% home bonus still lands under ~74 u/s on track 1.
 */
export interface CarStatIdentity {
  readonly n: number;
  readonly homePlanetId: string;
  readonly worldAdvantage: WorldAdvantage;
  readonly perk: CarPerkId;
  readonly stats: VehicleStats;
}

function identity(
  n: number,
  homePlanetId: string,
  worldAdvantage: WorldAdvantage,
  perk: CarPerkId,
  stats: VehicleStats,
): CarStatIdentity {
  return { n, homePlanetId, worldAdvantage, perk, stats };
}

/** Handling tuple used to prove no cloned Marauder blocks. */
export function handlingTuple(stats: VehicleStats): string {
  return `${stats.maxSpeed}|${stats.enginePower}|${stats.grip}|${stats.steerRate}`;
}

/**
 * Overlay authored physics onto a sheet without touching measured collision.
 */
export function overlayAuthoredStats(existing: VehicleStats, authored: VehicleStats): VehicleStats {
  return {
    ...authored,
    collisionRadius: existing.collisionRadius,
    collisionAlong: existing.collisionAlong,
    collisionAcross: existing.collisionAcross,
    collisionSquareMin: existing.collisionSquareMin,
    collisionSquareMax: existing.collisionSquareMax,
    collisionSquare: existing.collisionSquare,
  };
}

